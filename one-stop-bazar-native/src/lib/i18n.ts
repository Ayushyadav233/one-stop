export type StrKey = keyof typeof STR;

/** Component hook — re-renders on language change. */
export function useT(): (k: StrKey) => string {
  const language = useOSB((s) => s.language);
  return (k) => STR[k][language] ?? STR[k].en;
}

/** Template version — replaces {vars} (e.g. tx(l, "refTitle", { pts: 100, rs: 10 })). */
export function tx(language: Lang, k: StrKey, vars?: Record<string, string | number>): string {
  let s: string = STR[k][language] ?? STR[k].en;
  if (vars) for (const [kk, vv] of Object.entries(vars)) s = s.split(`{${kk}}`).join(String(vv));
  return s;
}

/** Component hook version of tx — re-renders on language change. */
export function useTx(): (k: StrKey, vars?: Record<string, string | number>) => string {
  const language = useOSB((s) => s.language);
  return (k, vars) => tx(language, k, vars);
}

/** Non-hook read (event handlers, NAV table). */
export function tFor(language: Lang, k: StrKey): string {
  return STR[k][language] ?? STR[k].en;
}
